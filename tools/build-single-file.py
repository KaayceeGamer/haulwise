#!/usr/bin/env python3
"""Builds supabase/dashboard/submit-single-file.ts from functions/submit/{index,parse}.ts, for pasting
into the Supabase dashboard editor. Run after changing either file: python3 tools/build-single-file.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / "supabase"
index = (root / "functions/submit/index.ts").read_text()
parse = (root / "functions/submit/parse.ts").read_text()
head, _, body = index.partition('import { parseExport } from "./parse.ts";\n')
parse = re.sub(r"^export ", "", parse, flags=re.M)
out = ("// Haulwise upload function, all in one file for pasting into the Supabase dashboard editor.\n"
       "// Generated by tools/build-single-file.py from functions/submit/. Don't edit by hand.\n"
       + head + "\n" + parse.rstrip() + "\n" + body)
(root / "dashboard/submit-single-file.ts").write_text(out)
print("wrote", len(out), "bytes")
