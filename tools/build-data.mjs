// Downloads the pooled community data and writes it into Data.lua, so every release of the
// addon ships with everyone's drop rates. Run by .github/workflows/community-data.yml.
//   SUPABASE_URL=https://xxxx.supabase.co SUPABASE_PUBLISHABLE_KEY=sb_publishable_... node tools/build-data.mjs
import { readFileSync, writeFileSync, appendFileSync } from "node:fs";

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) throw new Error("Set SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY");

const res = await fetch(`${url}/rest/v1/rpc/community_export`, {
  method: "POST",
  headers: { apikey: key, "Content-Type": "application/json" },
  body: "{}",
});
if (!res.ok) throw new Error(`Supabase answered ${res.status}: ${await res.text()}`);
const data = await res.json();
if (typeof data !== "string" || !/^CF[12],community,/.test(data)) throw new Error("Unexpected answer: " + String(data).slice(0, 200));
// Trainer and vendor positions (migration 003), appended as P records. Older databases lack it.
let places = "";
const pres = await fetch(`${url}/rest/v1/rpc/community_places_export`, {
  method: "POST",
  headers: { apikey: key, "Content-Type": "application/json" },
  body: "{}",
});
if (pres.ok) {
  const p = await pres.json();
  if (typeof p === "string" && /^(P,[^;]*)(;P,[^;]*)*$/.test(p)) places = p;
} else {
  console.log(`No community places yet (${pres.status}).`);
}
// Recipes and their reagents (migration 005), appended as C records.
let crafts = "";
const cres = await fetch(`${url}/rest/v1/rpc/community_crafts_export`, {
  method: "POST",
  headers: { apikey: key, "Content-Type": "application/json" },
  body: "{}",
});
if (cres.ok) {
  const c = await cres.json();
  if (typeof c === "string" && /^(C,[^;]*)(;C,[^;]*)*$/.test(c)) crafts = c;
} else {
  console.log(`No community recipes yet (${cres.status}).`);
}
const full = [data, places, crafts].filter(Boolean).join(";");
if (full.includes("]==]")) throw new Error("Data contains the Lua string terminator");

const file = new URL("../Data.lua", import.meta.url);
// Compare without the timestamp, so an unchanged pool doesn't trigger a release.
const oldData = (readFileSync(file, "utf8").match(/\[==\[([\s\S]*)\]==\]/) || [])[1] || "";
const strip = (s) => s.replace(/^CF[12],community,Community,\d+/, "");
const changed = strip(oldData) !== strip(full);

const players = Number(data.split(";")[0].split(",")[5] || 0);
const mobs = data.split(";").length - 1;
const nPlaces = places ? places.split(";").length : 0;
const nCrafts = crafts ? crafts.split(";").length : 0;
writeFileSync(file, `-- Community drop data, pooled from every player who uploads at the Haulwise site.
-- Generated by tools/build-data.mjs before each release. Don't edit by hand.
-- ${players} players, ${mobs} records, ${nPlaces} trainer and vendor positions, ${nCrafts} recipes.
Haulwise_Community = [==[${full}]==]
`);
console.log(`${changed ? "Updated" : "No change in"} community data: ${players} players, ${mobs} records, ${nPlaces} places, ${nCrafts} recipes.`);
if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `changed=${changed}\n`);
