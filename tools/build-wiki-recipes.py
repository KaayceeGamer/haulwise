#!/usr/bin/env python3
"""Build HaulwiseData/WikiRecipes.lua: how each WoW Forever recipe is learned (trainer, vendor,
drop, quest...) and the skill it needs, from Warcraft Wiki's "Forever ... recipes" pages.

Warcraft Wiki (https://warcraft.wiki.gg) text is licensed under CC BY-SA 4.0; this file is an
adaptation of those tables (only name, skill, new-in-Forever and source type are kept).

Usage: python3 tools/build-wiki-recipes.py [out file]
Fetches eight pages through the wiki's API (one request each, a second apart), so run it when
the data is rebuilt, not on a schedule.
"""
import json, os, re, sys, time, urllib.parse, urllib.request

PAGES = [
    "Forever alchemy recipes", "Forever blacksmithing plans", "Forever cooking recipes",
    "Forever enchanting formulas", "Forever engineering schematics", "Forever first aid recipes",
    "Forever leatherworking patterns", "Forever tailoring patterns",
]
API = "https://warcraft.wiki.gg/api.php"
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "HaulwiseData", "WikiRecipes.lua")

# Source column -> one letter: Trainer, Vendor, Drop, Quest, Automatic (learned with the skill),
# Reputation, Crafted/discovered, Other. "?" (the wiki doesn't know yet) is left out.
CODES = [("trainer", "T"), ("vendor", "V"), ("drop", "D"), ("quest", "Q"), ("automatic", "A"),
         ("reputation", "R"), ("discover", "C"), ("craft", "C")]

def fetch(page):
    q = urllib.parse.urlencode({"action": "parse", "page": page, "prop": "wikitext|revid", "format": "json"})
    req = urllib.request.Request(API + "?" + q, headers={"User-Agent": "Haulwise data build (https://github.com/KaayceeGamer/haulwise)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        d = json.load(r)["parse"]
    return d["wikitext"]["*"], d["revid"]

def clean(cell):
    cell = re.sub(r"\{\{text\|[^|}]*\|([^}]*)\}\}", r"\1", cell)
    cell = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]*)\]\]", r"\1", cell)
    cell = re.sub(r"\{\{[^}]*\}\}", "", cell)
    return re.sub(r"<[^>]+>", "", cell).strip()

recipes, revs = {}, []
for page in PAGES:
    text, rev = fetch(page)
    revs.append((page, rev))
    for line in text.split("\n"):
        if not line.startswith("| ") or "||" not in line:
            continue
        cells = [clean(c) for c in line[2:].split("||")]
        if len(cells) < 3:
            continue
        name, skill = cells[0], cells[1]
        if not name or not skill.isdigit():
            continue
        new = any(c.upper() == "NEW" for c in cells[2:-1])
        src = cells[-1].lower()
        code = next((c for k, c in CODES if k in src), None)
        key = name.lower()
        if key in recipes:      # the same recipe at two skills: keep the lower one
            continue
        recipes[key] = (int(skill), code or "", 1 if new else 0)
    time.sleep(1)

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')

lines = [
    "-- Haulwise Data: how WoW Forever's recipes are learned and the skill they need.",
    "-- Adapted from Warcraft Wiki (https://warcraft.wiki.gg), CC BY-SA 4.0",
    "-- (https://creativecommons.org/licenses/by-sa/4.0/): name, skill, new in Forever and source",
    "-- type from the pages below. Thanks to the Warcraft Wiki editors. Generated by",
    "-- tools/build-wiki-recipes.py; changes: tables reduced to those four columns.",
]
for page, rev in revs:
    lines.append("--   %s (revision %d)" % (page, rev))
lines += [
    "-- [lowercase recipe name] = \"skill:source:new\"  (source: T trainer, V vendor, D drop, Q quest,",
    "--   A automatic, R reputation, C crafted/discovered, empty = not known yet)",
    "HaulwiseData = HaulwiseData or {}",
    "HaulwiseData.wikiRecipes = {",
]
for key in sorted(recipes):
    skill, code, new = recipes[key]
    lines.append('    ["%s"] = "%d:%s:%d",' % (esc(key), skill, code, new))
lines.append("}")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("recipes", len(recipes), "->", out)
